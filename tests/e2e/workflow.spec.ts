import {test,expect} from '@playwright/test';

test('interactive demo, persistent scan, evidence, search, case workflow, and mobile',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByText('DEMO DATA · FICTIONAL DEVICE')).toBeVisible();
 await expect(page.getByRole('heading',{name:'Your device. Understood.'})).toBeVisible();
 await page.getByRole('button',{name:'Inspect Storage',exact:true}).click();
 await expect(page.locator('.inspector h2')).toHaveText('Storage');
 await page.getByRole('button',{name:'Run diagnostic scan',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'Run simulated scan'}).click();
 await expect(page.getByText('Simulated scan · completed')).toBeVisible({timeout:15000});
 await page.reload();
 await page.getByRole('button',{name:'History',exact:true}).click();
 await expect(page.locator('.history-row').first()).toContainText('completed');
 await page.keyboard.press('Control+k');
 await page.getByRole('button',{name:'Search repair cases'}).click();
 await page.getByRole('textbox',{name:'Search repair cases'}).fill('battery');
 await expect(page.locator('.case-row')).toHaveCount(2);
 await page.getByRole('button',{name:'Create case',exact:true}).click();
 const dialog=page.getByRole('dialog');
 for(const [name,value] of Object.entries({title:'Browser verification repair',brand:'Lenovo',model:'ThinkPad T14 Gen 2',symptom:'Power intermittently disconnects',fault_group:'power'})) await dialog.locator(`[name="${name}"]`).fill(value);
 const created=page.waitForResponse(r=>r.url().endsWith('/api/cases')&&r.request().method()==='POST');
 await dialog.getByRole('button',{name:'Create case file'}).click();
 const createdId=(await (await created).json()).id;
 await expect(dialog.getByRole('heading',{name:'Browser verification repair',exact:true})).toBeVisible();
 const entry=async(kind:string,notes:string,result?:string)=>{await dialog.getByRole('combobox',{name:'Entry type',exact:true}).selectOption(kind);await dialog.getByLabel('Notes / reasoning').fill(notes);if(result)await dialog.getByRole('combobox',{name:'Result',exact:true}).selectOption(result)};
 await entry('test','Adapter output measured intermittent','fail');await dialog.getByRole('button',{name:'Append to case history'}).click();
 await expect(dialog.locator('.timeline-event')).toHaveCount(2);
 // Retrieve the persisted evidence ID, then exercise the browser transition forms.
 const response=await page.request.get('/api/cases/'+createdId);const caseData=await response.json();const testId=caseData.events.at(-1).id;
 await entry('confirmed_cause','Measured adapter output supports adapter failure');await dialog.getByLabel('Supporting test').fill(String(testId));await dialog.getByRole('button',{name:'Append to case history'}).click();
 await expect(dialog.locator('.workflow .current')).toHaveText('diagnosed');
 await entry('repair','Replaced adapter');await dialog.getByLabel('Replacement part').fill('OEM adapter');await dialog.getByRole('button',{name:'Append to case history'}).click();
 await expect(dialog.locator('.workflow .current')).toHaveText('repaired');
 await entry('post_test','Stable operation on replacement adapter','pass');await dialog.getByRole('button',{name:'Append to case history'}).click();
 await expect(dialog.locator('.workflow .current')).toHaveText('post tested');
 await entry('review','Reviewed evidence and test results','approved');await dialog.getByLabel('Reviewer name').fill('Browser reviewer');await dialog.getByRole('button',{name:'Append to case history'}).click();
 await expect(dialog.locator('.workflow .current')).toHaveText('approved');
 await entry('handover','Working when returned');await dialog.getByRole('button',{name:'Append to case history'}).click();
 await expect(dialog.locator('.workflow .current')).toHaveText('handover');
 await entry('follow_up','Owner confirmed stable operation','working');await dialog.getByRole('button',{name:'Append to case history'}).click();
 await expect(dialog.getByText('confirmed working at follow-up',{exact:false}).first()).toBeVisible();
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Workbench',exact:true}).click();
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await page.screenshot({path:'test-results/workbench-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await page.locator('.mobile-components').getByRole('button',{name:/Memory/}).click();
 await expect(page.locator('.inspector h2')).toHaveText('Memory');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.screenshot({path:'test-results/workbench-mobile.png',fullPage:true});
 expect(errors).toEqual([]);
});

test('unavailable and no-warning scenarios, partial cancellation, compare, and official source',async({page})=>{
 await page.goto('/');
 const scan=async(scenario:string)=>{await page.getByRole('button',{name:'Run diagnostic scan',exact:true}).click();await page.getByRole('dialog').getByRole('combobox').selectOption(scenario);await page.getByRole('button',{name:'Run simulated scan'}).click();await expect(page.getByRole('dialog')).toBeHidden()};
 await scan('unavailable');await expect(page.getByText('Simulated scan · completed')).toBeVisible({timeout:15000});
 await expect(page.locator('.inspector .state-label')).toHaveText('Data unavailable');
 await expect(page.locator('.finding')).toHaveCount(0);
 await scan('healthy');await expect(page.getByText('Simulated scan · completed')).toBeVisible({timeout:15000});
 await expect(page.locator('.inspector .state-label')).toHaveText('No warning detected');
 await expect(page.locator('.finding')).toHaveCount(0);
 await scan('warning');await expect(page.locator('.scan-progress span')).toContainText('battery');
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(page.getByText('Simulated scan · cancelled')).toBeVisible({timeout:15000});
 await page.getByRole('button',{name:'Evidence',exact:true}).click();
 await expect(page.locator('tbody tr').first()).toBeVisible();
 expect(await page.locator('tbody tr').count()).toBeLessThan(13);
 await page.getByRole('button',{name:'Repair Library',exact:true}).click();
 await page.getByRole('checkbox',{name:'Compare Fan obstruction under sustained load',exact:true}).check();
 await page.getByRole('checkbox',{name:'Compare Short runtime with declining battery capacity',exact:true}).check();
 await page.getByRole('button',{name:'Compare selected (2/2)'}).click();
 await expect(page.locator('.comparison>div')).toHaveCount(2);
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Advisories',exact:true}).click();
 await expect(page.getByText(/Live manufacturer retrieval is not configured/)).toBeVisible();
 await page.getByRole('button',{name:'Add official source',exact:true}).click();
 await page.getByRole('dialog').getByLabel('Title',{exact:true}).fill('Official Lenovo support');
 await page.getByLabel('Official HTTPS URL').fill('https://support.lenovo.com/');
 await page.getByLabel('Applicability / version notes').fill('Select the exact T14 Gen 2 variant on the official support site.');
 await page.getByRole('button',{name:'Save source bookmark'}).click();
 await expect(page.getByRole('link',{name:'Official Lenovo support'}).first()).toBeVisible();
 await page.getByRole('button',{name:'Workbench',exact:true}).click();
 await scan('warning');await expect(page.getByText('Simulated scan · completed')).toBeVisible({timeout:15000});
});
